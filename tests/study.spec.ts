test('practice cards and session setup use readable high-contrast text', async ({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Practice questions',exact:true}).click();
 await page.screenshot({path:'/tmp/radia-practice.png',fullPage:true});
 const contrast = async (selector:string) => page.locator(selector).first().evaluate(el=>{
   const values = (s:string) => (s.match(/[\d.]+/g)||[]).slice(0,3).map(Number).map(v=>{v/=255;return v<=.04045?v/12.92:((v+.055)/1.055)**2.4;});
   const luminance = (s:string) => {const [r,g,b]=values(s);return .2126*r+.7152*g+.0722*b;};
   let parent:Element|null=el;let background='rgb(255, 255, 255)';
   while(parent){const value=getComputedStyle(parent).backgroundColor;if(value!=='rgba(0, 0, 0, 0)'&&value!=='transparent'){background=value;break;}parent=parent.parentElement;}
   const a=luminance(getComputedStyle(el).color),b=luminance(background);return (Math.max(a,b)+.05)/(Math.min(a,b)+.05);
 });
 for(const selector of ['.practice-mode-card.green h2','.practice-mode-card.green p','.practice-mode-card.cream h2','.practice-mode-card.cream p']) expect(await contrast(selector),selector).toBeGreaterThanOrEqual(4.5);
 await page.getByRole('button',{name:'Start practice',exact:true}).click();
 for(const selector of ['.setup-modal h2','.setup-modal>p','.field-label','.field-label select','.timer-input input']) expect(await contrast(selector).catch(()=>0),selector).toBeGreaterThanOrEqual(4.5);
 await page.screenshot({path:'/tmp/radia-setup-final.png'});
});

